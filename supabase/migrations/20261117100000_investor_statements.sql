-- كشوف المستثمرين الشهرية: رسوم الإدارة لكل شاليه، كشف مُقفل لكل شهر، وسجل التوزيعات.

-- رسوم الإدارة (نسبة من الإيرادات المحصّلة) تُخصم قبل التوزيع على الشركاء
alter table public.chalets add column if not exists mgmt_fee_pct numeric not null default 0
  check (mgmt_fee_pct >= 0 and mgmt_fee_pct <= 100);

-- نسخة ثابتة من كشف الشهر وقت الإقفال: ما تتغير لو تعدّلت حجوزات أو مصاريف بعدها
create table if not exists public.investor_statements (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default current_owner_id(),
  chalet text not null,
  period text not null check (period ~ '^[0-9]{4}-[0-9]{2}$'),
  revenue numeric not null default 0,
  bookings_count int not null default 0,
  expenses jsonb not null default '{}'::jsonb,
  expenses_total numeric not null default 0,
  mgmt_fee_pct numeric not null default 0,
  mgmt_fee numeric not null default 0,
  net numeric not null default 0,
  shares jsonb not null default '[]'::jsonb,
  reserve_spent numeric not null default 0,
  note text,
  closed_at timestamptz not null default now(),
  closed_by text,
  unique (owner_id, chalet, period)
);
alter table public.investor_statements enable row level security;
drop policy if exists investor_statements_tenant_isolation on public.investor_statements;
create policy investor_statements_tenant_isolation on public.investor_statements for all
  using (owner_id = current_owner_id() or is_platform_admin())
  with check (owner_id = current_owner_id() or is_platform_admin());

-- التوزيعات: طريقة الدفع وإيصال التحويل، وowner_id لأن db() يضيفه تلقائياً عند الإضافة
alter table public.investor_payments add column if not exists owner_id uuid default current_owner_id();
alter table public.investor_payments add column if not exists method text;
alter table public.investor_payments add column if not exists receipt_url text;
update public.investor_payments p set owner_id = i.owner_id from public.investors i where i.id = p.investor_id and p.owner_id is null;
create index if not exists investor_payments_investor_id_idx on public.investor_payments(investor_id);
